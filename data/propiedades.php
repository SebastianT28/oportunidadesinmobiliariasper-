function findProperty(string $slug): ?array {
    global $terrenos, $casas, $departamentos, $alquileres;
    foreach (array_merge($terrenos, $casas, $departamentos, $alquileres) as $p) {
        if ($p['slug'] === $slug) return $p;
    }
    return null;
}

function relatedProperties(string $categoria, string $currentSlug, int $limit = 3): array {
    global $terrenos, $casas, $departamentos, $alquileres;
    $pool = match($categoria) {
        'terrenos'      => $terrenos,
        'casas'         => $casas,
        'departamentos' => $departamentos,
        'alquiler'      => $alquileres,
        default         => [],
    };
    return array_slice(array_filter($pool, fn($p) => $p['slug'] !== $currentSlug), 0, $limit);
}
